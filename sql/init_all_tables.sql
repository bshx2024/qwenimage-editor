-- 1. User Info Table
CREATE TABLE IF NOT EXISTS user_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    user_id VARCHAR UNIQUE,
    name VARCHAR,
    email VARCHAR UNIQUE,
    image VARCHAR,
    last_login_ip VARCHAR,
    first_source VARCHAR(64) DEFAULT '',
    first_medium VARCHAR(64) DEFAULT '',
    first_campaign VARCHAR(128) DEFAULT '',
    first_referrer VARCHAR(255) DEFAULT '',
    first_landing VARCHAR(255) DEFAULT '',
    first_touch_at BIGINT DEFAULT 0,
    last_source VARCHAR(64) DEFAULT '',
    last_medium VARCHAR(64) DEFAULT '',
    last_campaign VARCHAR(128) DEFAULT '',
    register_country VARCHAR(64) DEFAULT '',
    register_device VARCHAR(32) DEFAULT '',
    register_os VARCHAR(32) DEFAULT '',
    register_browser VARCHAR(32) DEFAULT '',
    register_lang VARCHAR(32) DEFAULT ''
);

-- 2. User Available Credits Table
CREATE TABLE IF NOT EXISTS user_available (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    user_id VARCHAR UNIQUE,
    stripe_customer_id VARCHAR,
    available_times INTEGER DEFAULT 2
);

-- 3. Stripe Customers Table
CREATE TABLE IF NOT EXISTS stripe_customers (
    user_id VARCHAR NOT NULL PRIMARY KEY,
    stripe_customer_id TEXT
);

-- 4. Stripe Subscriptions Table
DO $$ BEGIN
    CREATE TYPE subscription_status AS ENUM (
        'trialing', 'active', 'canceled', 'incomplete', 'incomplete_expired', 'past_due', 'unpaid', 'paused'
    );
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

CREATE TABLE IF NOT EXISTS stripe_subscriptions (
    id TEXT NOT NULL PRIMARY KEY,
    user_id VARCHAR,
    status subscription_status,
    metadata JSONB,
    price_id TEXT,
    quantity INTEGER,
    cancel_at_period_end BOOLEAN,
    created TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    current_period_start TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    current_period_end TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    cancel_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    canceled_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    trial_start TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    trial_end TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 5. Works / Generations Table
CREATE TABLE IF NOT EXISTS works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    uid VARCHAR UNIQUE,
    input_text VARCHAR,
    revised_text VARCHAR,
    output_url VARCHAR,
    input_image_url VARCHAR,
    task_type VARCHAR DEFAULT 'text2img',
    is_public BOOLEAN DEFAULT false,
    status INTEGER DEFAULT 1,
    user_id VARCHAR,
    is_origin BOOLEAN DEFAULT true,
    origin_language VARCHAR DEFAULT 'en',
    current_language VARCHAR DEFAULT 'en',
    is_delete BOOLEAN DEFAULT false
);

-- 6. Key Value Store Table (for Stripe idempotency)
CREATE TABLE IF NOT EXISTS key_value (
    key VARCHAR NOT NULL PRIMARY KEY,
    value VARCHAR
);

-- 7. Search Logs Table
CREATE TABLE IF NOT EXISTS search_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    search_text VARCHAR,
    result_count VARCHAR,
    user_agent VARCHAR,
    search_ip VARCHAR
);

-- 8. Sensitive Words Table
CREATE TABLE IF NOT EXISTS sensitive_words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    words VARCHAR NOT NULL,
    level VARCHAR DEFAULT '1'
);

-- 9. Bot Crawl Logs Table
CREATE TABLE IF NOT EXISTS bot_crawl_logs (
    id SERIAL PRIMARY KEY,
    bot_type VARCHAR(64) NOT NULL,
    ip VARCHAR(64) NOT NULL,
    path TEXT NOT NULL,
    user_agent TEXT,
    is_verified BOOLEAN DEFAULT FALSE,
    is_content_page BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Genuine Visitor Logs Table
CREATE TABLE IF NOT EXISTS genuine_visitor_logs (
    id SERIAL PRIMARY KEY,
    source VARCHAR(64) NOT NULL,
    ip VARCHAR(64) NOT NULL,
    country VARCHAR(64) DEFAULT 'Unknown',
    landing_path TEXT NOT NULL,
    referer TEXT,
    user_agent TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. User Survey Logs Table
CREATE TABLE IF NOT EXISTS user_survey_logs (
    id SERIAL PRIMARY KEY,
    user_id VARCHAR(128) NOT NULL,
    user_email VARCHAR(255),
    use_case VARCHAR(128) NOT NULL,
    priority VARCHAR(128),
    source VARCHAR(64) DEFAULT 'web',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Payment Orders Table
CREATE TABLE IF NOT EXISTS payment_orders (
    id SERIAL PRIMARY KEY,
    order_id VARCHAR(128) UNIQUE NOT NULL,
    provider VARCHAR(32) NOT NULL DEFAULT 'waffo',
    user_id VARCHAR(128) NOT NULL,
    user_email VARCHAR(255),
    amount NUMERIC(10, 2),
    currency VARCHAR(16) DEFAULT 'USD',
    status VARCHAR(32) NOT NULL,
    plan_id VARCHAR(128),
    credits_added INTEGER DEFAULT 0,
    raw_payload JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Create Indexes for Optimal Performance
CREATE INDEX IF NOT EXISTS idx_works_uid ON works(uid);
CREATE INDEX IF NOT EXISTS idx_works_user_id ON works(user_id);
CREATE INDEX IF NOT EXISTS idx_works_created_at ON works(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_user_info_user_id ON user_info(user_id);
CREATE INDEX IF NOT EXISTS idx_user_info_email ON user_info(email);
CREATE INDEX IF NOT EXISTS idx_user_available_user_id ON user_available(user_id);
CREATE INDEX IF NOT EXISTS idx_bot_crawl_type_date ON bot_crawl_logs(bot_type, created_at);
CREATE INDEX IF NOT EXISTS idx_genuine_visitor_source_date ON genuine_visitor_logs(source, created_at);
CREATE INDEX IF NOT EXISTS idx_user_survey_user_id ON user_survey_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_payment_orders_user ON payment_orders(user_id);

